            DB::table('blogs')->where('id', $blog->id)->update(['slug' => $oldSlug]);

            DB::table('blog_translations')
                ->where('blog_id', $blog->id)
                ->where('locale', 'ar')
                ->delete();
        }

        DB::table('slug_redirects')
            ->where('from_slug', $oldSlug)
            ->where('type', 'blog')
            ->delete();
    }
};
